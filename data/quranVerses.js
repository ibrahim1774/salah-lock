// Helper function to get a random verse
export const getRandomVerse = () => {
  const randomIndex = Math.floor(Math.random() * QURAN_VERSES.length);
  return QURAN_VERSES[randomIndex];
};

// Helper function to get verse by ID
export const getVerseById = (id) => {
  return QURAN_VERSES.find(verse => verse.id === id);
};

// Helper function to get all verses
export const getAllVerses = () => {
  return QURAN_VERSES;
};

// Get a verse based on day of year (consistent for the entire day)
export const getDailyVerse = (date = new Date()) => {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const verseIndex = dayOfYear % QURAN_VERSES.length;
  return QURAN_VERSES[verseIndex];
};
